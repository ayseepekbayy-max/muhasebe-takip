CREATE TABLE "PrivateMediaContents" (
    "MessageId" integer NOT NULL,
    "MediaKey" character varying(32) NOT NULL,
    "Payload" bytea NOT NULL,
    "CreatedAtUtc" timestamp with time zone NOT NULL,
    "ExpiresAtUtc" timestamp with time zone NOT NULL,
    CONSTRAINT "PK_PrivateMediaContents" PRIMARY KEY ("MessageId"),
    CONSTRAINT "CK_PrivateMediaContent_Expiry" CHECK ("ExpiresAtUtc" - "CreatedAtUtc" = interval '24 hours'),
